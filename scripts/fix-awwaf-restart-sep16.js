// WRITE script — user-confirmed correction, 2026-09-16.
//
// Awwaf (AC-CUST-00182, prepaid, Dinner 200) paused his subscription
// effective 2026-08-31, but the daily prepaid-anniversary cron had already
// generated his September invoice (AC-INV-01481, AED 200, full month)
// earlier that same morning before the pause was recorded — so he was
// wrongly billed a full month he never used.
//
// User's decision: void that September invoice entirely (he wasn't served
// any part of September), and restart him as a brand-new subscription from
// TODAY (2026-09-16) since he's paying again today. Per this app's
// established convention (see changeSubscriptionPlan / Switch Plan), a
// restart never mutates the old row's start_date in place — it closes the
// old row for good and opens a fresh one, so July/August's already-paid
// billing history stays untouched.
const fs = require('fs')
for (const line of fs.readFileSync('.env.local', 'utf8').split('\n')) {
  const m = line.match(/^([^#=]+)=(.*)$/)
  if (m) process.env[m[1].trim()] = m[2].trim().replace(/^["']|["']$/g, '')
}
const { createClient } = require('@supabase/supabase-js')
const admin = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY, { auth: { autoRefreshToken: false, persistSession: false } })

const CUSTOMER_ID    = '7e870f6e-25af-4e54-a36a-7c67f880178d' // Awwaf, AC-CUST-00182
const OLD_SUB_ID     = '9dc28b84-a50f-4901-a075-764ea30c3940' // Dinner 200, paused, 2026-07-01 -> 2026-08-31
const PLAN_ID        = 'a221ee43-ddcd-4c1d-8ee2-ff441f5bf5e7' // Dinner 200 plan
const BAD_INVOICE_ID = '1b9e2844-1a62-4b66-911a-1fde12f6ab1f' // AC-INV-01481, Sep 2026
const OWNER_ID       = 'a277b0b4-7869-4c7f-bab3-99b522d249f3' // Tabrez Nakhwa (owner)
const TODAY          = '2026-09-16'
const NEW_PERIOD_END = '2026-10-15'
const PRICE          = 200

async function main() {
  // 0. Re-verify preconditions
  const { data: cust, error: custErr } = await admin.from('customers').select('id, full_name, customer_code, payment_terms').eq('id', CUSTOMER_ID).single()
  if (custErr || !cust) throw new Error(`Customer lookup failed: ${custErr?.message}`)
  if (cust.customer_code !== 'AC-CUST-00182') throw new Error(`Expected AC-CUST-00182, got ${cust.customer_code} — aborting`)

  const { data: inv, error: invErr } = await admin.from('invoices').select('*').eq('id', BAD_INVOICE_ID).single()
  if (invErr || !inv) throw new Error(`Invoice lookup failed: ${invErr?.message}`)
  if (inv.invoice_number !== 'AC-INV-01481') throw new Error(`Expected AC-INV-01481, got ${inv.invoice_number} — aborting`)
  if (inv.status !== 'issued') throw new Error(`Expected status 'issued', got ${inv.status} — aborting`)
  if (String(inv.total_amount) !== '200.00' && Number(inv.total_amount) !== 200) throw new Error(`Expected total 200, got ${inv.total_amount} — aborting`)

  const { data: oldSub, error: oldSubErr } = await admin.from('customer_subscriptions').select('*').eq('id', OLD_SUB_ID).single()
  if (oldSubErr || !oldSub) throw new Error(`Old subscription lookup failed: ${oldSubErr?.message}`)
  if (oldSub.status !== 'paused' || oldSub.end_date !== '2026-08-31') throw new Error(`Old subscription no longer matches expected paused/2026-08-31 state — aborting`)

  const { data: ledgerRows } = await admin
    .from('ledger_entries')
    .select('id, debit_amount')
    .eq('reference_table', 'invoices')
    .eq('reference_id', BAD_INVOICE_ID)
    .is('reversal_of', null)
  console.log('Preconditions OK.')
  console.log('Bad invoice:', inv.invoice_number, inv.total_amount, inv.status)
  console.log('Ledger entries to reverse:', ledgerRows)

  // 1. Void the wrongly-issued September invoice
  const { error: voidErr } = await admin
    .from('invoices')
    .update({
      status: 'cancelled',
      notes: `Voided ${TODAY}: subscription was paused effective 2026-08-31 before this invoice's period even started — customer was not served any part of September. Generated by the daily prepaid cron before the pause was recorded. He is restarting fresh from ${TODAY} — see new invoice on the new subscription.`,
    })
    .eq('id', BAD_INVOICE_ID)
    .eq('status', 'issued')
  if (voidErr) throw new Error(`Void failed: ${voidErr.message}`)
  console.log('Voided AC-INV-01481')

  // 2. Reverse its ledger debit (insert a correction entry, never edit/delete the original)
  for (const entry of ledgerRows ?? []) {
    const { error: ledgerErr } = await admin.from('ledger_entries').insert({
      customer_id: CUSTOMER_ID,
      entry_date: TODAY,
      entry_type: 'invoice',
      debit_amount: '0.00',
      credit_amount: entry.debit_amount,
      description: `Correction: AC-INV-01481 voided — customer paused before September and never served that month`,
      reference_table: 'invoices',
      reference_id: BAD_INVOICE_ID,
      reversal_of: entry.id,
      created_by: OWNER_ID,
    })
    if (ledgerErr) throw new Error(`Ledger reversal failed: ${ledgerErr.message}`)
    console.log('Reversed ledger debit of', entry.debit_amount, 'for AC-INV-01481')
  }

  // 3. Close the old subscription row for good (was 'paused' — mark
  // 'completed' so the UI's Resume button on this row can never reactivate
  // it and collide with the fresh row created below).
  const { error: closeErr } = await admin
    .from('customer_subscriptions')
    .update({ status: 'completed' })
    .eq('id', OLD_SUB_ID)
    .eq('status', 'paused')
  if (closeErr) throw new Error(`Closing old subscription failed: ${closeErr.message}`)
  console.log('Closed old subscription (paused -> completed)')

  // 4. Open a fresh subscription starting today
  const { data: newSub, error: newSubErr } = await admin
    .from('customer_subscriptions')
    .insert({
      customer_id: CUSTOMER_ID,
      fixed_plan_id: PLAN_ID,
      start_date: TODAY,
      end_date: null,
      agreed_monthly_price: PRICE.toFixed(2),
      meal_prices: null,
      status: 'active',
      notes: `Restarted ${TODAY} after Aug 31 pause, per staff request`,
      created_by: OWNER_ID,
    })
    .select('id')
    .single()
  if (newSubErr || !newSub) throw new Error(`New subscription insert failed: ${newSubErr?.message}`)
  console.log('Created new subscription:', newSub.id)

  // 5. Issue the first invoice on the new cycle so he can pay today
  const { data: settingsRow } = await admin.from('app_settings').select('vat_percent').eq('id', 1).single()
  const vatRate = parseFloat(String(settingsRow?.vat_percent ?? '5'))
  const taxAmount = (PRICE * vatRate) / (100 + vatRate)

  const { data: invoiceNumber, error: numErr } = await admin.rpc('next_invoice_number')
  if (numErr || !invoiceNumber) throw new Error(`Invoice number generation failed: ${numErr?.message}`)

  const { data: newInvoice, error: newInvErr } = await admin
    .from('invoices')
    .insert({
      invoice_number: invoiceNumber,
      customer_id: CUSTOMER_ID,
      invoice_date: TODAY,
      due_date: TODAY,
      invoice_type: 'fixed_monthly',
      billing_period_start: TODAY,
      billing_period_end: NEW_PERIOD_END,
      subtotal: PRICE.toFixed(2),
      discount_amount: '0.00',
      tax_amount: taxAmount.toFixed(2),
      total_amount: PRICE.toFixed(2),
      status: 'issued',
      notes: `First cycle of restarted subscription (see ${OLD_SUB_ID} for prior cycle, ended 2026-08-31)`,
      created_by: OWNER_ID,
    })
    .select('id')
    .single()
  if (newInvErr || !newInvoice) throw new Error(`New invoice insert failed: ${newInvErr?.message}`)
  console.log('Created new invoice:', invoiceNumber, newInvoice.id)

  const { error: itemErr } = await admin.from('invoice_items').insert({
    invoice_id: newInvoice.id,
    order_id: null,
    description: `Monthly Fixed Plan — Dinner 200 — 16 Sep to 15 Oct 2026 (restart cycle)`,
    quantity: '1',
    unit_price: PRICE.toFixed(2),
    total_price: PRICE.toFixed(2),
  })
  if (itemErr) throw new Error(`Invoice item insert failed: ${itemErr.message}`)
  console.log('Added invoice line item')

  const { error: ledgerInsErr } = await admin.from('ledger_entries').insert({
    customer_id: CUSTOMER_ID,
    entry_date: TODAY,
    entry_type: 'invoice',
    debit_amount: PRICE.toFixed(2),
    credit_amount: '0.00',
    description: `Invoice ${invoiceNumber}`,
    reference_table: 'invoices',
    reference_id: newInvoice.id,
    created_by: OWNER_ID,
  })
  if (ledgerInsErr) throw new Error(`New ledger debit insert failed: ${ledgerInsErr.message}`)
  console.log('Inserted ledger debit for new invoice')

  console.log('\nDone.')
  console.log('- AC-INV-01481 (Sep, wrongly billed) -> cancelled, ledger reversed')
  console.log('- Old subscription', OLD_SUB_ID, '-> completed')
  console.log('- New subscription', newSub.id, 'active from', TODAY)
  console.log('- New invoice', invoiceNumber, 'issued for', TODAY, '->', NEW_PERIOD_END, 'AED', PRICE, '(awaiting his payment today)')
}

main().catch(e => { console.error('FAILED:', e.message); process.exit(1) })
